name = "Анна"
age = 20
price = 1250.567

# Способ 1: f-строка
result1 = f"Студент: {name}, возраст: {age} лет"

# Способ 2: метод format()
result2 = "Студент: {}, возраст: {} лет".format(name, age)

print(result1)
print(result2)

# Позиционные поля {}

result = "Имя: {}, возраст: {}".format(name, age)
print(result)

result = "Возраст: {1}, имя: {0}".format(name, age)
print(result)

# Именованные поля {name}

result = "Студент: {student}, возраст: {years}".format(student=name, years=age)
print(result)

# Указание формата числа

# f-строка: 2 знака после запятой
print(f"Цена: {price:.2f}")

# format(): 2 знака после запятой
print("Цена: {:.2f}".format(price))

# 5. Преимущества и недостатки

# f-строки:
# + Короткие и легко читаются.
# + Удобно вставлять переменные и выражения.
# - Значения подставляются сразу при создании строки.
# - Шаблон нельзя использовать как независимый формат с последующей передачей разных аргументов.

# format():
# + Можно хранить шаблон в переменной.
# + Можно подставлять значения позже.
# + Поддерживает позиционные и именованные поля.
# - Запись иногда получается длиннее.
# - При большом количестве аргументов менее удобен для чтения.