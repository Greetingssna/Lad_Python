try:
    rating = float(input("Введите рейтинг фильма: "))

    verdict = "Рекомендуем" if rating >= 7 else "Пропустить"

    print(verdict)
except ValueError:
    print("Ошибка. Введите число")

# здесь логично использовать тернарный оператор, потому что нужно выбрать всего из двух вариантов
# (рекомендуем или пропустить). он позволяет записать простую строку в одну строчку.

